/* Print current time to Virtual Terminal */
void print_time(char *task_name)
{
    char buffer[64];

    int len = snprintf(
        buffer,
        sizeof(buffer),
        "[%lu ms] %s\r\n",
        (unsigned long)get_time(),
        task_name
    );

    if (len > 0 && len < sizeof(buffer))
    {
        HAL_UART_Transmit(
            &huart1,
            (uint8_t *)buffer,
            len,
            100
        );
    }
}

/* Task runs every 10ms */
